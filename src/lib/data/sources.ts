/**
 * Source records for the preview dataset.
 *
 * Every displayed value traces back to a source record with its own status (ADR-0008 / the
 * source-admission lifecycle in the architecture overview). Nothing here is a rights approval:
 * operator sites are recorded as *planned* primary sources and reference sources are recorded with
 * their licence and verification date so the resort page can attribute them honestly.
 */

import type { SourceRef } from '../domain/types.js';

/** Date the resort facts in this dataset were read from their reference sources. */
const REFERENCE_READ_AT = '2026-10-12T16:40:00.000Z';

/**
 * The illustrative sample adapter. This is not a live feed and it is not permitted production
 * data: it exists so the product UI, freshness display and scoring path can be exercised from a
 * deterministic dataset while source rights are still pending.
 */
export const SAMPLE_CONDITIONS_SOURCE: SourceRef = {
	id: 'sample-conditions',
	kind: 'sample-conditions',
	url: 'https://github.com/lassepehkonen/nordic-ski-intelligence/blob/main/src/lib/data/conditions.ts',
	status: 'illustrative',
	retrievedAt: REFERENCE_READ_AT,
	license: null,
	note: 'Deterministic sample observations generated by this repository for UI development. Not a live resort or weather feed.'
};

export function operatorSiteSource(slug: string, url: string): SourceRef {
	return {
		id: `site-${slug}`,
		kind: 'operator-site',
		url,
		status: 'rights_pending',
		retrievedAt: null,
		license: null,
		note: 'Planned primary source for live conditions and lift/piste status. No automated collection, caching or commercial display has been approved yet.'
	};
}

export function wikipediaSource(
	id: string,
	url: string,
	language: string,
	note: string | null = null
): SourceRef {
	return {
		id,
		kind: 'reference',
		url,
		status: 'rights_pending',
		retrievedAt: REFERENCE_READ_AT,
		license: `CC BY-SA 4.0 (${language} Wikipedia)`,
		note: note ?? 'Resort identity and advertised resort figures read from this article.'
	};
}

/** Date the OpenSkiData snapshot and Fnugg API responses below were actually read. */
const OPEN_SOURCE_READ_AT = '2026-10-13T16:15:00.000Z';

/**
 * OpenSkiData static ski-area snapshot, verified against the live daily build on the read date.
 * Usage terms: ODbL with multi-source attribution (OpenSkiData/OpenSkiMap, © OpenStreetMap
 * contributors, Skimap.org, Who's On First, © Mapterhorn), automated download at most once per
 * day, hosted vector tiles may not be consumed directly. Not a live-conditions source.
 */
export function openSkiDataSource(): SourceRef {
	return {
		id: 'openskidata',
		kind: 'reference',
		url: 'https://openskidata.org/',
		status: 'rights_pending',
		retrievedAt: OPEN_SOURCE_READ_AT,
		license: 'ODbL (OSM, Skimap.org, Who’s On First, Mapterhorn attribution required)',
		note: 'Static resort/run/lift geometry and statistics. Weekly or less refresh; metadata.json checked before each download.'
	};
}

/**
 * Fnugg v1 open API for Norwegian resorts. Verified live on the read date: resort record with
 * slopes/lifts lists and open counts, conditions (yr.no-reported weather + snow), season dates.
 * Usage terms: data must be attributed to fnugg.no, consent is revocable, and the data may not be
 * used in a service "essentially identical to fnugg.no" — this comparison product needs the
 * owner's written waiver before any commercial redisplay (ADR-0008 gate still applies).
 */
export function fnuggSource(resortId: number): SourceRef {
	return {
		id: `fnugg-${resortId}`,
		kind: 'reference',
		url: 'https://api.fnugg.no/docs/v1',
		status: 'rights_pending',
		retrievedAt: OPEN_SOURCE_READ_AT,
		license: null,
		note: 'Norwegian resort conditions/lift-slope status via the open Fnugg API. Attribution to fnugg.no required; written waiver needed before production use.'
	};
}

export const REFERENCE_READ_DATE = REFERENCE_READ_AT;
